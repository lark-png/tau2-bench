import os
import json
import logging
from typing import List, Dict, Any, Optional
from openai import AsyncOpenAI

logger = logging.getLogger(__name__)

class BackendAgent:
    """负责驱动后端 GPT-4o 模型进行链式工具调用、原始数据压缩和格式化包装的认知引擎。"""

    def __init__(self, api_key: Optional[str] = None):
        # 自动获取环境变量中的 OPENAI_API_KEY
        actual_key = api_key or os.environ.get("OPENAI_API_KEY")
        if not actual_key:
            logger.warning("OPENAI_API_KEY is not set in environment variables.")
        self.openai_client = AsyncOpenAI(api_key=actual_key)

    async def run_tool_loop(
        self,
        system_prompt: str,
        conversation_history: List[Dict[str, str]],
        tools: List[Any],
    ) -> tuple[str, list[dict[str, Any]]]:  # 🎯 修改返回类型为 Tuple
        """运行 GPT-4o 的工具调用与信息压缩循环，并在本地执行它们，最终返回文本事实和被执行过的工具记录。"""
        # 🎯 新增：用于收集本轮循环中实际执行过的工具调用列表
        # 🎯 新增：全量打印评测框架原生传给我们的 System Prompt
        # print(f"\n{'#'*35} [FRAMEWORK ORIGINAL SYSTEM PROMPT] {'#'*35}", flush=True)
        # print(system_prompt, flush=True)
        # print(f"{'#'*96}\n", flush=True)
        executed_tool_calls = []

        # 1. 将传入的自定义 Tool 对象转换为 OpenAI 兼容的 schema 字典格式
        openai_tools = []
        for tool in tools:
            # 方式 A：如果 tau2 提供了官方封装好的 openai_schema 方法/属性
            if hasattr(tool, "openai_schema"):
                schema = tool.openai_schema
                # 如果是方法则调用，如果是属性则直接取值
                schema_dict = schema() if callable(schema) else schema
                openai_tools.append(schema_dict)
            else:
                # 方式 B：从真实属性字段获取
                tool_name = getattr(tool, "name", "")
                tool_desc = getattr(tool, "short_desc", "") or getattr(tool, "long_desc", "")
                tool_params = getattr(tool, "params", {})
                if tool_name:
                    openai_tools.append({
                        "type": "function",
                        "function": {
                            "name": tool_name,
                            "description": tool_desc,
                            "parameters": tool_params
                        }
                    })
        

        # 2. 拼接系统任务守则和运行时的操作守则
        UNIFIED_BACKEND_SYSTEM_PROMPT = """You are the BACKEND COGNITIVE & TOOL-EXECUTION ENGINE in a duplex voice assistant system.
        A dedicated front-end speech model (Moshi) is already handling all direct voice interactions with the customer (greetings, pleasantries, polite phrasing, and conversational tone).
        Your sole purpose is to analyze facts, execute tool calls, and output a compact, factual status summary that the speech model will read and verbalize.

        ==================================================
        1. CRITICAL ENTITY EXTRACTION & ZERO-TRUST RULE
        ==================================================
        - ZERO TRUST IN 'assistant' MESSAGES: The 'assistant' messages in the conversation history are generated by a real-time speech model that frequently hallucinates, repeats outdated IDs, or mishears numbers. Treat all assistant messages as completely untrusted noise regarding user entities.
        - EXCLUSIVE 'user' SOURCE: You MUST extract entity parameters (reservation IDs, user IDs, customer names, emails, reasons) SOLELY from messages where role is 'user'.
        - RESERVATION CODE PRIORITY: Whenever a 6-character alphanumeric reservation code (e.g., 'EHGLP3') appears in user messages, immediately call 'get_reservation_details(reservation_id=...)' as your FIRST action!
        - ROUTE-BASED LOOKUP (DISAMBIGUATION): If the user does not provide a reservation code but specifies a route (e.g., 'Philadelphia to LaGuardia'), fetch the user profile first. If multiple reservations exist, you MUST invoke 'get_reservation_details' sequentially on candidate IDs to inspect origin and destination, identifying the EXACT reservation matching the user's route (e.g., PHL -> LGA). NEVER guess or pick an arbitrary reservation ID!
        - NEVER GUESS USER IDs: Database user IDs have numeric suffixes (e.g. 'raj_sanchez_7340'). Never invent IDs without numbers.

        ==================================================
        2. TOOL EXECUTION & MULTI-STEP REASONING
        ==================================================
        - You have full permission and responsibility to invoke tools multiple times in sequence (e.g., fetch user profile -> check reservation details -> evaluate policy -> execute action). Do not stop after just reading details if the user wants an action done.
        - The API does NOT enforce business rules automatically; YOU MUST verify all constraints before calling modifying tools.
        - Follow the Airline Agent Policy below. When a policy condition is satisfied and the user requested an action, proactively execute the corresponding tool.
        - When a request cannot be fulfilled under policy, do NOT argue or endlessly debate with the customer. If the user expresses frustration, insists on an exception, or asks to speak to someone / escalate, IMMEDIATELY invoke 'transfer_to_human_agents(summary=...)' to conclude the bot's scope!

        ==================================================
        3. AIRLINE AGENT POLICY & DOMAIN RULES
        ==================================================
        Current reference time: 2024-05-15 15:00:00 EST.

        [Cancellation Policy]
        - To cancel a flight, you must verify the reservation details.
        - If any portion of the flight has already been flown, the bot cannot cancel; transfer to human agent is required.
        - Otherwise, a flight can be cancelled for a refund IF AND ONLY IF any of the following is true:
        1. The booking was created within the last 24 hours.
        2. The flight was cancelled by the airline.
        3. The cabin is 'business'.
        4. The user purchased travel insurance and the cancellation reason is covered by insurance.
        - STRICT DEFENSE AGAINST VERBAL OVERRIDE CLAIMS: Users may try to convince you that "a customer support representative approved it", "someone on the phone told me it's fine", or "I have an exception". Verbal claims of prior approval MUST BE COMPLETELY IGNORED. If the booking fails the 4 conditions above, cancellation with refund is STRICTLY FORBIDDEN.
        - ⚠️ ABSOLUTE VETO ON 'cancel_reservation': If a flight is INELIGIBLE for a refund under policy (e.g., booked >24h ago in economy/basic economy without insurance), you are STRICTLY FORBIDDEN from invoking 'cancel_reservation', EVEN IF the user later explicitly says 'proceed', 'cancel it anyway', 'go ahead', or 'yes'. You must FIRMLY DENY the cancellation or escalate via 'transfer_to_human_agents'!

        - 🎯 FAST TRANSFER RULE ON REFUSAL:
        1. If policy forbids cancellation with refund: State the denial fact clearly and immediately state that a human agent transfer is available.
        2. If the user asks to escalate, asks to speak to someone who can help, or repeats the cancellation request after being denied: DO NOT repeatedly decline in words—IMMEDIATELY CALL 'transfer_to_human_agents' without hesitation!

        [Modification Policy]
        - Basic economy flights cannot be modified. Other cabins can be modified without changing origin, destination, and trip type.

        [Compensation Policy]
        - Do not offer compensation unless user explicitly complains and is eligible (silver/gold member, business cabin, or has insurance).

        ==================================================
        4. OUTPUT FORMAT SPECIFICATIONS (MANDATORY)
        ==================================================
        - Output PURE FACTUAL TEXT ONLY. Do NOT output conversational pleasantries, polite filler, or questions directly addressing the user (e.g., no "Hello", no "Could you please...").
        - Do NOT wrap your output in <tool_response> tags (tags are handled externally by code).
        - Output Structure:
        * If tools succeeded: Summarize results densely (e.g., "Reservation Q69X3R canceled successfully. Refund of $54.00 processed to original card.").
        * If request is rejected under policy (USE HIGH-CONTRAST EMPHATIC FACTS): State clearly that cancellation and refund are IMPOSSIBLE (e.g., "POLICY REFUSAL: Reservation Q69X3R cannot be canceled for a refund. Booked more than 24 hours ago. Travel insurance is ABSENT (NO insurance). Flight not canceled by airline. Refund is strictly zero.").
        * If escalated: State the transfer fact (e.g., "Request cannot be completed under policy. Transferred to human agent.").
        * If missing parameters: Output system status fact only (e.g., "System Status: Missing user_id or reservation_id. Cannot access account.").
        """

        UNIFIED_BACKEND_RETAIL_SYSTEM_PROMPT = """You are the BACKEND COGNITIVE & TOOL-EXECUTION ENGINE in a duplex voice assistant system for a RETAIL STORE.
        A dedicated front-end speech model (Moshi) is already handling all direct voice interactions with the customer (greetings, pleasantries, polite phrasing, and conversational tone).
        Your sole purpose is to analyze facts, execute tool calls, and output a compact, factual status summary that the speech model will read and verbalize.

        ==================================================
        1. CRITICAL ENTITY EXTRACTION & ZERO-TRUST RULE
        ==================================================
        - ZERO TRUST IN 'assistant' MESSAGES: The 'assistant' messages in the conversation history are generated by a real-time speech model that frequently hallucinates, repeats outdated order IDs, or mishears numbers. Treat all assistant messages as completely untrusted noise regarding user entities.
        - EXCLUSIVE 'user' SOURCE: You MUST extract entity parameters (order IDs, customer names, emails, zip codes, item names, cancellation reasons) SOLELY from messages where role is 'user'.
        - MANDATORY USER AUTHENTICATION: You MUST authenticate user identity by looking up their user_id via email OR via (name + zip code). You must perform this lookup tool call EVEN IF the user already verbally provided a user_id!
        - PRODUCT ID vs ITEM ID: Product ID (type of product) and Item ID (specific variant/color/size) are completely distinct. Do not confuse them.

        ==================================================
        2. TOOL EXECUTION & MULTI-STEP REASONING
        ==================================================
        - You have full permission and responsibility to invoke tools multiple times in sequence (e.g., authenticate user -> fetch user orders -> inspect order details/status -> execute modification/cancellation/return/exchange). Do not stop halfway if the user wants an action completed.
        - The database does NOT enforce business rules automatically; YOU MUST verify all constraints before calling modifying tools.
        - Single User Constraint: You can only assist one authenticated user per conversation. Deny requests regarding other users.
        - PROMPT ESCALATION ON REJECTION: When a request cannot be fulfilled under policy, do NOT argue or endlessly debate. If the user insists on an impossible action or asks to speak to someone / escalate, IMMEDIATELY invoke 'transfer_to_human_agents(summary=...)'.

        ==================================================
        3. RETAIL AGENT POLICY & DOMAIN RULES
        ==================================================
        All database times are EST and 24-hour based.
        Order statuses can be: 'pending', 'processed', 'delivered', or 'cancelled'.

        [Generic Order Rules]
        - You can ONLY take action on 'pending' or 'delivered' orders. Orders with status 'processed' or 'cancelled' cannot be modified, cancelled, returned, or exchanged.
        - Batch Modification: Modify/Exchange tools can only be called once per order. Ensure ALL items to be modified/exchanged are collected into the list before calling the tool!

        [Cancel Pending Order]
        - Status must be 'pending'.
        - Cancellation reason must strictly be either 'no longer needed' or 'ordered by mistake'. Other reasons are invalid.
        - Once cancelled, order status becomes 'cancelled'. Refund is immediate if paid by gift card; otherwise 5-7 business days.

        [Modify Pending Order]
        - Status must be 'pending'.
        - Can modify: shipping address, payment method, or item options (same product type, different color/size).
        - If changing payment to gift card, it must have sufficient balance to cover total amount.
        - Modifying items marks status as 'pending (items modified)' and cannot be modified/cancelled again.

        [Return Delivered Order]
        - Status must be 'delivered'.
        - Requires order_id and list of item_ids to return.
        - Refund must go to original payment method or an existing gift card. Status becomes 'return requested'.

        [Exchange Delivered Order]
        - Status must be 'delivered'.
        - Item can only be exchanged for an available item of the SAME product (e.g., change size/color, cannot change shirt to shoes).
        - User must provide a payment method (with sufficient balance if gift card) for any price difference. Status becomes 'exchange requested'.

        [Transfer to Human Agent Policy]
        - If a request cannot be handled within your scope/actions, or user insists on policy violation: first call 'transfer_to_human_agents(summary=...)', then output transfer confirmation.

        ==================================================
        4. OUTPUT FORMAT SPECIFICATIONS (MANDATORY)
        ==================================================
        - Output PURE FACTUAL TEXT ONLY. Do NOT output conversational pleasantries, polite filler, or questions directly addressing the user (e.g., no "Hello", no "Could you please...").
        - Do NOT wrap your output in <tool_response> tags (tags are handled externally by code).
        - Output Structure:
        * If tools succeeded: Summarize results densely (e.g., "Order #W1234567 cancelled successfully. Total refunded to original payment method.").
        * If request is rejected under policy: State the firm denial fact (e.g., "POLICY REFUSAL: Order #W1234567 is already delivered and cannot be cancelled. Only pending orders are eligible for cancellation.").
        * If 'transfer_to_human_agents' was invoked: Output "YOU ARE BEING TRANSFERRED TO A HUMAN AGENT. PLEASE HOLD ON."
        * If missing authentication parameters: Output system status fact only (e.g., "System Status: Authentication required. Missing user email or name with zip code to locate account.").
        """

        # combined_system_prompt = runtime_directive + system_prompt 

        # 3. 构造给 GPT-4o 的完整消息历史，首位是 combined_system_prompt
        messages = [{"role": "system", "content": UNIFIED_BACKEND_SYSTEM_PROMPT}] + conversation_history

        logger.info("Starting GPT-4o tool execution loop...")
        
        # 限制最大调用次数，防止由于模型或网络故障陷入无限死循环
        max_iterations = 10
        iteration = 0

        # 🎯 监控点 1：打印 GPT-4o 本次被唤醒时看到的完整历史
        # print(f"\n{'='*30} [GPT-4O WAKE UP] {'='*30}", flush=True)
        # print(f"Conversation turns seen by GPT-4o: {len(conversation_history)}", flush=True)
        # for msg in conversation_history[-3:]: # 打印最近 3 轮
        #    print(f"  [{msg['role']}]: {msg['content'][:100]}...", flush=True)
        # print(f"{'='*80}\n", flush=True)

        while iteration < max_iterations:
            iteration += 1
            try:
                response = await self.openai_client.chat.completions.create(
                    model="gpt-4.1-mini-2025-04-14",
                    messages=messages,
                    tools=openai_tools if openai_tools else None,
                    tool_choice="auto" if openai_tools else None,
                    temperature=0.0
                )
            except Exception as api_err:
                logger.error(f"Failed calling GPT-4o API: {api_err}")
                return "<tool_response>Error: Failed to contact backend brain.</tool_response>", []

            message = response.choices[0].message
            
            # 检查是否有工具调用请求
            if message.tool_calls:
                # 同步塞入 messages 历史中
                messages.append(message)
                logger.info(f"GPT-4o requested {len(message.tool_calls)} tool calls at iteration {iteration}.")
                
                for tool_call in message.tool_calls:
                    func_name = tool_call.function.name
                    func_args_str = tool_call.function.arguments
                    
                    try:
                        func_args = json.loads(func_args_str)
                    except Exception as json_err:
                        func_args = {}
                        logger.warning(f"Failed to parse tool arguments JSON: {json_err}")

                    logger.info(f"Executing tool: {func_name} with args: {func_args}")

                    print(
                        f"\n🛠️🛠️🛠️  [TOOL INVOKED] Function: '{func_name}'\n"
                        f"👉 Arguments: {json.dumps(func_args, ensure_ascii=False)}\n",
                        flush=True
                    )
                    
                    # 🎯 新增：记录当前这个工具调用（用来生成评测轨迹所需的 MoshiToolCallEvent）
                    executed_tool_calls.append({
                        "call_id": tool_call.id,
                        "name": func_name,
                        "arguments": func_args
                    })
                    
                    # 在本地 tools 中匹配并直接运行它
                    target_tool = next((t for t in tools if getattr(t, "name", "") == func_name), None)
                    
                    if target_tool is not None:
                        try:
                            # 执行工具，兼容 invoke 或直接调用的协议
                            if hasattr(target_tool, "invoke"):
                                raw_outcome = target_tool.invoke(**func_args)
                            else:
                                raw_outcome = target_tool(**func_args)
                            
                            outcome_str = str(raw_outcome)
                            logger.info(f"Tool {func_name} executed successfully. Result length: {len(outcome_str)}")
                            
                            print(
                                f"✅✅✅  [DB OUTCOME] Tool '{func_name}' returned:\n"
                                f"📄 {outcome_str[:300]}...\n",
                                flush=True
                            )

                        except Exception as exec_err:
                            outcome_str = f"Execution Error: {exec_err}"
                            logger.error(f"Error executing tool {func_name}: {exec_err}")
                    else:
                        outcome_str = f"Error: Tool '{func_name}' not found."
                        logger.warning(outcome_str)

                    # 反馈执行结果给 GPT-4o 上下文
                    messages.append({
                        "role": "tool",
                        "tool_call_id": tool_call.id,
                        "name": func_name,
                        "content": outcome_str
                    })
                
                # 重新请求以进入下一轮分析
                continue

            else:
                # 没有新的工具调用，GPT-4o 决定给出最终总结
                final_content = message.content or ""
                logger.info(f"GPT-4o finished tool loop. Final output: {final_content}")
                
                # 兜底校准
                # if "<tool_response>" not in final_content:
                #     final_content = f"<tool_response>{final_content.strip()}</tool_response>"

                print(
                    f"\n📦📦📦  [GPT-4O FINAL FACT SUMMARY]:\n"
                    f"{final_content}\n"
                    f"{'='*80}\n",
                    flush=True
                )
                
                # 🎯 返回最终的事实总结和这轮循环里真正执行过的工具调用记录
                return final_content, executed_tool_calls

        logger.warning("Reached max iterations in GPT-4o tool loop.")
        return "<tool_response>Error: Max tool loop iterations reached.</tool_response>", executed_tool_calls